import re
from typing import Any, Dict, List, Optional, Tuple
from pydantic import BaseModel, Field

PAPER_ID_PATTERN = re.compile(r"^P\d{3,}$", re.IGNORECASE)


class PaperSummary(BaseModel):
    paper_id: str
    title: str
    authors: List[str]
    year: int = Field(..., ge=1900, le=2030)
    topic: str


class SearchResult(BaseModel):
    query: str
    year_from: int = Field(..., ge=1900, le=2030)
    count: int = Field(..., ge=0)
    results: List[PaperSummary]


class PaperDetails(BaseModel):
    paper_id: str
    title: str
    authors: List[str]
    year: int = Field(..., ge=1900, le=2030)
    venue: str
    topic: str
    abstract: str


class PaperMetrics(BaseModel):
    paper_id: str
    title: str
    datasets: List[str]
    metrics: Dict[str, str]
    main_finding: str


class StructuredPaperAnalysis(BaseModel):
    """Validated structured output generated by the LLM for paper summaries."""

    paper_id: str = Field(..., min_length=2)
    title: str = Field(..., min_length=3)
    research_area: str = Field(..., min_length=2)
    key_contributions: List[str] = Field(..., min_length=1)
    reported_metrics: Dict[str, str] = Field(default_factory=dict)
    practical_takeaway: str = Field(..., min_length=5)


def validate_tool_args(tool_name: str, args: Dict[str, Any]) -> Tuple[bool, Optional[str]]:
    """Validates tool arguments before executing any repository function."""
    if not isinstance(args, dict):
        return False, "Tool arguments must be provided as a JSON object / dictionary."

    if tool_name == "search_papers":
        query = args.get("query")
        year_from = args.get("year_from", 2020)

        if not isinstance(query, str) or not query.strip():
            return False, "Invalid argument: 'query' must be a non-empty string."
        if isinstance(year_from, bool) or not isinstance(year_from, int):
            return False, "Invalid argument: 'year_from' must be an integer."
        if year_from < 1900 or year_from > 2030:
            return False, "Invalid argument: 'year_from' must be between 1900 and 2030."
        return True, None

    if tool_name in ("get_paper_details", "extract_key_metrics"):
        paper_id = args.get("paper_id")
        if not isinstance(paper_id, str) or not paper_id.strip():
            return False, "Invalid argument: 'paper_id' must be a non-empty string."
        if not PAPER_ID_PATTERN.match(paper_id.strip()):
            return (
                False,
                f"Invalid argument: 'paper_id' ('{paper_id}') must match format 'P001' (e.g., P001, P004).",
            )
        return True, None

    return False, f"Unknown tool name: '{tool_name}'."